def _collect_aliases(alias_key: str) -> set[str]:
    aliases = set()
    for book_data in BIBLE_BOOK_ABBREVIATION_MAP.values():
        aliases.update(book_data.get(alias_key, []))
    return aliases


def get_all_english_aliases():
    return sorted(_collect_aliases("english_aliases"))


def get_all_spanish_aliases():
    return sorted(_collect_aliases("spanish_aliases"))


def get_all_reference_aliases(include_spanish=True, include_shared=True):
    aliases = set(get_all_english_aliases())
    if include_spanish:
        aliases.update(get_all_spanish_aliases())
    if include_shared:
        aliases.update(_collect_aliases("shared_aliases"))
    return sorted(aliases, key=lambda alias: (-len(alias), alias.casefold(), alias))


def get_book_code_for_alias(alias):
    if alias is None:
        return None

    normalized = str(alias).strip().casefold()
    if not normalized:
        return None

    for book_data in BIBLE_BOOK_ABBREVIATION_MAP.values():
        candidates = (
            book_data.get("english_aliases", [])
            + book_data.get("spanish_aliases", [])
            + book_data.get("shared_aliases", [])
        )
        if any(candidate.casefold() == normalized for candidate in candidates):
            return book_data.get("recommended_workflow_code")

    return None


